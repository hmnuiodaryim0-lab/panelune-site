#!/usr/bin/env python3
"""Generate crawlable HTML from one release setting; standard library only."""
import argparse
import json
from html import escape
from pathlib import Path
from xml.sax.saxutils import escape as xml_escape

ROOT = Path(__file__).resolve().parents[1]
LANGS = ('en', 'zh-Hans', 'zh-Hant', 'ja', 'ko')

def read(name):
    return json.loads((ROOT / 'content' / (name + '.json')).read_text())

def head(config, title, description, path, prefix, lang='en', alternates=False):
    base = config['baseUrl']
    canonical = base + path
    result = f'''<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)}</title>
<meta name="description" content="{escape(description)}">
<link rel="canonical" href="{canonical}">
<meta property="og:title" content="{escape(title)}">
<meta property="og:description" content="{escape(description)}">
<meta property="og:type" content="website">
<meta property="og:url" content="{canonical}">
<meta property="og:site_name" content="Panelune">
<meta property="og:locale" content="{read(lang)['locale']}">
<meta property="og:image" content="{base}assets/social.jpg">
<meta property="og:image:width" content="1024">
<meta property="og:image:height" content="1024">
<meta property="og:image:alt" content="Panelune app icon">
<meta name="twitter:card" content="summary">
<meta name="twitter:title" content="{escape(title)}">
<meta name="twitter:description" content="{escape(description)}">
<meta name="twitter:image" content="{base}assets/social.jpg">
<meta name="twitter:image:alt" content="Panelune app icon">
<meta name="theme-color" content="#ffffff">
<link rel="icon" type="image/png" sizes="32x32" href="{prefix}assets/favicon-32.png">
<link rel="apple-touch-icon" sizes="180x180" href="{prefix}assets/apple-touch-icon.png">
<link rel="stylesheet" href="{prefix}styles.css">
'''
    if alternates:
        for code in LANGS:
            result += f'<link rel="alternate" hreflang="{code}" href="{base}{"" if code == "en" else code + "/"}">\n'
        result += f'<link rel="alternate" hreflang="x-default" href="{base}">\n'
    return result

def homepage(config, lang):
    d = read(lang)
    live = config['iphoneReleaseStatus'] == 'available'
    state = 'live' if live else 'soon'
    prefix = '' if lang == 'en' else '../'
    path = '' if lang == 'en' else lang + '/'
    t = lambda key: escape(d[key])
    home = './' if lang == 'en' else '../'
    nav = f'<a href="#features">{escape(d["nav"][0])}</a><a href="{prefix}privacy.html" hreflang="en">{escape(d["nav"][1])}</a><a href="{prefix}support.html" hreflang="en">{escape(d["nav"][2])}</a>'
    languages = ''
    for code in LANGS:
        href = prefix + ('' if code == 'en' else code + '/')
        href = href or './'
        current = ' aria-current="page"' if code == lang else ''
        languages += f'<a data-language="{code}" href="{href}" lang="{code}" hreflang="{code}"{current}>{escape(read(code)["name"])}</a>'
    schema = {
        '@context': 'https://schema.org', '@type': 'SoftwareApplication', 'name': 'Panelune',
        'url': config['baseUrl'], 'downloadUrl': config['appStoreUrl'],
        'applicationCategory': 'LifestyleApplication',
        'operatingSystem': 'iOS, iPadOS' if live else 'iPadOS',
        'availableOnDevice': ['iPhone','iPad'] if live else ['iPad'],
        'softwareVersion': config['launchVersion'] if live else config['releasedVersion'],
        'inLanguage': list(LANGS), 'description': d['description'],
        'image': config['baseUrl']+'assets/app-icon.png',
    }
    features = '\n'.join(f'<article class="feature"><h3>{escape(title)}</h3><p>{escape(body)}</p></article>' for title, body in d['features'])
    phone = ''
    for i, name in enumerate(('library','manga','novel','import'),1):
        phone += f'''<figure><img src="{prefix}assets/screenshots/{lang}-{name}.webp" srcset="{prefix}assets/screenshots/{lang}-{name}-small.webp 536w, {prefix}assets/screenshots/{lang}-{name}.webp 804w" sizes="(max-width: 430px) 300px, (max-width: 760px) calc((100vw - 58px) / 2), (max-width: 1176px) calc((100vw - 116px) / 4), 265px" width="804" height="1748" loading="lazy" decoding="async" alt="{escape(d['alts'][i])}"><figcaption>{escape(d['captions'][i])}</figcaption></figure>\n'''
    return f'''<!doctype html>
<!-- Generated by scripts/build.py. Edit content/*.json instead. -->
<html lang="{lang}">
<head>
{head(config,d[state+'Title'],d['description'],path,prefix,lang,True)}<script type="application/ld+json">{json.dumps(schema,ensure_ascii=False)}</script>
<script src="{prefix}site.js" defer></script>
</head>
<body>
<a class="skip-link" href="#main">{t('skip')}</a>
<header class="site-header"><a class="brand" href="{home}">Panelune</a><nav class="nav" aria-label="Panelune">{nav}</nav></header>
<nav class="language-nav wrap" aria-label="{t('language')}">{languages}</nav>
<main id="main">
<section class="hero wrap" id="intro"><div class="eyebrow">{t(state+'Badge')}</div><h1>{t('hero')}<br><span>{t(state+'Hero')}</span></h1><p class="lead">{t('lead')}</p><div class="hero-actions"><a class="button" href="{config['appStoreUrl']}">{t('download')}</a><a class="text-link" href="#features">{t('explore')}</a></div><p class="release-note">{t(state+'Note')}</p></section>
<section class="screenshots wrap" id="screenshots" aria-labelledby="screenshots-heading"><div class="section-heading"><div class="eyebrow">{t(state+'Preview')}</div><h2 id="screenshots-heading">{t('screens')}</h2><p>{t('demo')}</p></div>
<figure class="ipad-shot"><img src="{prefix}assets/screenshots/ipad-library.webp" srcset="{prefix}assets/screenshots/ipad-library-small.webp 800w, {prefix}assets/screenshots/ipad-library.webp 1600w" sizes="(max-width: 760px) calc(100vw - 40px), (max-width: 956px) calc(100vw - 56px), 900px" width="1600" height="1200" loading="lazy" decoding="async" alt="{escape(d['alts'][0])}"><figcaption>{escape(d['captions'][0])}</figcaption></figure>
<div class="phone-gallery">{phone}</div></section>
<section class="section wrap" id="features"><div class="section-heading"><div class="eyebrow">{t('featuresEyebrow')}</div><h2>{t('featuresTitle')}</h2></div><div class="feature-grid">{features}</div><p class="reading-note">{t(state+'Reading')}</p></section>
<section class="section wrap" id="languages"><div class="section-heading"><h2>{t('languagesTitle')}</h2><p>{t('languagesText')}</p></div><p class="language-list"><span lang="en">English</span> · <span lang="zh-Hans">简体中文</span> · <span lang="zh-Hant">繁體中文</span> · <span lang="ja">日本語</span> · <span lang="ko">한국어</span></p></section>
<section class="section wrap" id="pro"><div class="pro"><div><div class="eyebrow">{t('proEyebrow')}</div><h2>Panelune Pro</h2><p>{t('proText')}</p><p class="purchase"><strong>{t('proPurchase')}</strong><br>{t('proPrice')}</p></div><a class="button" href="{prefix}support.html#pro">{t('proLink')}</a></div></section>
<div class="format wrap">{t('formats')} <a href="{prefix}support.html#formats">{t('compatibility')}</a>.</div>
<div class="disclaimer wrap">{t('disclaimer')}</div>
</main>
<footer class="site-footer"><div class="wrap footer-inner"><span>© 2026 Panelune</span><div class="footer-links"><a href="{prefix}privacy.html">{escape(d['nav'][1])}</a><a href="{prefix}support.html">{escape(d['nav'][2])}</a></div></div><p class="wrap legal-note">{t('legalNote')}</p></footer>
</body>
</html>
'''

def build(output=ROOT, status=None):
    config = read('site')
    if status is not None: config['iphoneReleaseStatus'] = status
    if config['iphoneReleaseStatus'] not in ('coming-soon','available'):
        raise ValueError('iphoneReleaseStatus must be coming-soon or available')
    output.mkdir(parents=True, exist_ok=True)
    for lang in LANGS:
        path = output / ('' if lang == 'en' else lang) / 'index.html'
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_text(homepage(config,lang),encoding='utf-8')
    for name,title,desc in (
        ('privacy','Privacy Policy — Panelune','How Panelune handles your library, local transfers, and purchases.'),
        ('support','Panelune Support','Get help with Panelune on iPad, upcoming iPhone support, file imports, Private Library, and restoring Panelune Pro purchases.' if config['iphoneReleaseStatus']=='coming-soon' else 'Get help with Panelune on iPhone and iPad, file imports, Private Library, and restoring Panelune Pro purchases.')
    ):
        template = (ROOT/'templates'/f'{name}.html').read_text()
        start,end = template.index('<head>'),template.index('</head>')+7
        template = template[:start]+'<head>\n'+head(config,title,desc,name+'.html','')+'</head>'+template[end:]
        availability = 'Panelune 1.2.0 is available on iPhone and iPad.' if config['iphoneReleaseStatus']=='available' else 'Panelune 1.1.1 is available on iPad. Version 1.2.0 has been submitted for Apple review; iPhone support is coming soon and is not yet available.'
        template = template.replace('{{availability}}',availability)
        (output/f'{name}.html').write_text(template,encoding='utf-8')
    urls = [config['baseUrl']+('' if lang=='en' else lang+'/') for lang in LANGS]
    urls += [config['baseUrl']+path+'.html' for path in ('privacy','support')]
    (output/'sitemap.xml').write_text('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'+''.join(f'  <url><loc>{xml_escape(url)}</loc></url>\n' for url in urls)+'</urlset>\n')
    (output/'robots.txt').write_text('User-agent: *\nAllow: /\n\nSitemap: '+config['baseUrl']+'sitemap.xml\n')
    basepath = '/' + config['baseUrl'].split('/',3)[3]
    (output/'404.html').write_text(f'''<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex"><title>Page not found — Panelune</title><link rel="stylesheet" href="{basepath}styles.css"><link rel="icon" href="{basepath}favicon.ico"></head><body><main class="prose wrap"><div class="eyebrow">Panelune · 404</div><h1>Page not found.</h1><p>The page may have moved. Your next read is still waiting.</p><a class="button" href="{basepath}">Back to Panelune</a><p><a href="{basepath}support.html">Get support</a> · <a href="{basepath}privacy.html">Privacy Policy</a></p></main></body></html>\n''')

if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=ROOT)
    args=parser.parse_args()
    build(args.output)
    print('Generated five language homepages, Privacy, Support, sitemap, robots and 404.')
